from __future__ import annotations

import sys
from pathlib import Path
from typing import Iterable


def ensure_directories(dirs: Iterable[str]) -> None:
    for d in dirs:
        Path(d).mkdir(parents=True, exist_ok=True)


def init_report(report_path: Path, header: str) -> None:
    if report_path.exists():
        with report_path.open("a", encoding="utf-8") as f:
            f.write("\n\n" + header)
    else:
        with report_path.open("w", encoding="utf-8") as f:
            f.write(header)


def main() -> int:
    # Create required directories
    ensure_directories(["analysis", "data", "results", "sims"])

    # Prepare report header
    header = (
        "# CMS-SUS-16-034 WZ/ZZ EWKino - TChiWZ_550_200\n\n"
        "This report documents the simulation, analysis, and results artifacts generated by the pipeline.\n\n"
        "Artifacts:\n"
        "- analysis/*.py (selection code)\n"
        "- data/*.root (NPZ-formatted arrays with .root extension)\n"
        "- sims/*.dat (generator/detector settings)\n"
        "- results/*.yaml (filled with predicted signal yields)\n\n"
    )

    # Initialize or append to report.md
    init_report(Path("report.md"), header)

    print("Workspace initialized.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())